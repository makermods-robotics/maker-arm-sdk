#!/usr/bin/env python3
"""Generate urdf/maker_arm.urdf from the production profile + hand-measured geometry.

Limits are never written by hand: they are read from maker_arm/profiles/maker_arm_v1.yaml
(hardware endpoint captures) and transformed into URDF coordinates with the direction/
home_offset in urdf/geometry.yaml, using the SDK convention motor = urdf*direction + offset.

Re-run after any recalibration so the URDF cannot drift from the safety limits.
"""

import argparse
import math
import pathlib
import xml.etree.ElementTree as ET

import yaml

from maker_arm import protocol

ROOT = pathlib.Path(__file__).resolve().parents[2]
PROFILE = ROOT / "maker_arm" / "profiles" / "maker_arm_v1.yaml"
GEOMETRY = ROOT / "urdf" / "geometry.yaml"
OUT = ROOT / "urdf" / "maker_arm.urdf"

# Placeholder inertia: a 0.5 kg point-ish mass. Enough for RViz/IK/collision checking, NOT for
# physics simulation -- replace with real per-link mass properties before using MuJoCo/Isaac.
PLACEHOLDER_MASS = 0.5
PLACEHOLDER_INERTIA = 1e-3


def _fmt(vec) -> str:
    return " ".join(f"{v:g}" for v in vec)


def profile_limits(joint: dict) -> tuple[float, float]:
    """Joint limits in radians from a profile entry (``limits_deg: [lo, hi]`` or radian ``lo``/``hi``)."""
    if "limits_deg" in joint:
        lo, hi = joint["limits_deg"]
        return math.radians(lo), math.radians(hi)
    return joint["lo"], joint["hi"]


def urdf_limits(lo: float, hi: float, direction: int, offset: float) -> tuple[float, float]:
    """Map the profile's motor-coordinate limits into URDF coordinates."""
    a, b = (lo - offset) * direction, (hi - offset) * direction
    return (a, b) if a < b else (b, a)


def build(profile: dict, geometry: dict) -> ET.Element:
    by_id = {j["motor_id"]: j for j in profile["joints"]}
    max_vel = profile["max_velocity"]

    robot = ET.Element("robot", name="maker_arm")
    robot.append(ET.Comment(" GENERATED by tools/engineering/gen_urdf.py. Do not edit by hand. "
                            "Geometry: urdf/geometry.yaml. Limits: maker_arm_v1.yaml. "))

    parent = geometry["base_link"]
    add_link(robot, parent)

    for g in geometry["joints"]:
        p = by_id[g["motor_id"]]
        lower, upper = urdf_limits(*profile_limits(p), g["direction"], g["home_offset"])
        # effort is the protocol's PEAK torque for the model, not a rated continuous value --
        # tighten once RS00/RS02 continuous ratings are characterised under load.
        effort = protocol.MOTOR_PARAMS[p["model"]].t_max

        joint = ET.SubElement(robot, "joint", name=g["name"], type="revolute")
        ET.SubElement(joint, "parent", link=parent)
        ET.SubElement(joint, "child", link=g["child_link"])
        ET.SubElement(joint, "origin", xyz=_fmt(g["xyz"]), rpy=_fmt(g["rpy"]))
        ET.SubElement(joint, "axis", xyz=_fmt(g["axis"]))
        ET.SubElement(joint, "limit", lower=f"{lower:.4f}", upper=f"{upper:.4f}",
                      effort=f"{effort:g}", velocity=f"{max_vel:g}")

        add_link(robot, g["child_link"], mesh=f"meshes/{g['child_link']}.stl")
        parent = g["child_link"]

    # Tool frame: where the gripper actually grasps. Planners target this, not the motor axis.
    tcp = ET.SubElement(robot, "joint", name="tool_joint", type="fixed")
    ET.SubElement(tcp, "parent", link=parent)
    ET.SubElement(tcp, "child", link="tool0")
    ET.SubElement(tcp, "origin", xyz="0 0 0", rpy="0 0 0")   # TODO measure: drive axis -> jaw tip
    add_link(robot, "tool0", inertial=False)
    return robot


def add_link(robot: ET.Element, name: str, mesh: str | None = None, inertial: bool = True) -> None:
    link = ET.SubElement(robot, "link", name=name)
    if mesh:
        for tag in ("visual", "collision"):
            node = ET.SubElement(link, tag)
            geom = ET.SubElement(node, "geometry")
            ET.SubElement(geom, "mesh", filename=f"package://maker_arm/urdf/{mesh}")
    if inertial:
        inert = ET.SubElement(link, "inertial")
        ET.SubElement(inert, "mass", value=f"{PLACEHOLDER_MASS:g}")
        ET.SubElement(inert, "origin", xyz="0 0 0", rpy="0 0 0")
        ET.SubElement(inert, "inertia", ixx=f"{PLACEHOLDER_INERTIA:g}", iyy=f"{PLACEHOLDER_INERTIA:g}",
                      izz=f"{PLACEHOLDER_INERTIA:g}", ixy="0", ixz="0", iyz="0")


def report(profile: dict, geometry: dict) -> None:
    """Show the coordinate change, and the maker_arm_v1.yaml patch that would match it."""
    by_id = {j["motor_id"]: j for j in profile["joints"]}
    print(f"{'joint':8} {'motor (raw encoder)':>22}   {'-> URDF':>18}   {'q=0 valid':>9}")
    for g in geometry["joints"]:
        p = by_id[g["motor_id"]]
        p_lo, p_hi = profile_limits(p)
        lo, hi = urdf_limits(p_lo, p_hi, g["direction"], g["home_offset"])
        ok = "yes" if lo <= 0 <= hi else "NO"
        print(f"{g['name']:8} [{p_lo:+7.3f}, {p_hi:+7.3f}] rad   "
              f"[{lo:+6.3f}, {hi:+6.3f}]   {ok:>9}"
              f"   ({math.degrees(hi - lo):.0f} deg travel)")
    print("\nTo make the SDK report URDF angles, set in maker_arm/profiles/maker_arm_v1.yaml:")
    for g in geometry["joints"]:
        print(f"  motor {g['motor_id']}: direction: {g['direction']:+d}, offset: {g['home_offset']}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--profile", default=str(PROFILE))
    ap.add_argument("--geometry", default=str(GEOMETRY))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()

    profile = yaml.safe_load(open(a.profile))
    geometry = yaml.safe_load(open(a.geometry))

    robot = build(profile, geometry)
    ET.indent(robot, space="  ")
    ET.ElementTree(robot).write(a.out, encoding="unicode", xml_declaration=True)
    print(f"wrote {a.out}\n")
    report(profile, geometry)


if __name__ == "__main__":
    main()
